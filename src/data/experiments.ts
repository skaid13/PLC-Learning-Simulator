import type { Experiment, IOEntry } from '../types';

const io = (labels: string[], terminals: number[]): IOEntry[] =>
  labels.map((label, i) => ({ label, terminal: terminals[i].toString().padStart(2, '0') }));
const inputs = (labels: string[], terminals = labels.map((_, i) => i)) =>
  io(labels, terminals).map((item) => ({ ...item, terminal: `I-${item.terminal}` }));
const outputs = (labels: string[], terminals = labels.map((_, i) => i)) =>
  io(labels, terminals).map((item) => ({ ...item, terminal: `O-${item.terminal}` }));

