import { it, expect, vi } from 'vitest';
import { render, screen, act } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { LearningDataTools } from './LearningDataTools';
import { createLearningBackup } from '../storage/learningBackup';
import * as projects from '../storage/projects';
it('读取备份只预览，取消不写；必须先保留当前备份并明确同意才能导入', async () => {
  const user = userEvent.setup();
  const download = vi.spyOn(projects, 'downloadText').mockImplementation(() => {});
  localStorage.setItem('plc-learning:guide:auto', 'false');
  const backup = createLearningBackup(localStorage);
  backup.records['plc-learning:guide:auto'] = 'true';
  render(<LearningDataTools />);
  act(() => window.dispatchEvent(new Event('plc-open-backup')));
  const file = new File([JSON.stringify(backup)], 'backup.json', { type: 'application/json' });
  Object.defineProperty(file, 'text', { value: async () => JSON.stringify(backup) });
  await user.upload(screen.getByLabelText('选择学习数据备份'), file);
  expect(await screen.findByText('将导入1项学习记录')).toBeInTheDocument();
  expect(localStorage.getItem('plc-learning:guide:auto')).toBe('false');
  const confirm = screen.getByRole('button', { name: '确认导入并重新打开首页' });
  expect(confirm).toBeDisabled();
  await user.click(screen.getByRole('checkbox'));
  expect(confirm).toBeDisabled();
  await user.click(screen.getByRole('button', { name: '导出全部学习数据' }));
  expect(download).toHaveBeenCalledOnce();
  expect(confirm).toBeEnabled();
  await user.click(screen.getByRole('button', { name: '取消导入' }));
  expect(localStorage.getItem('plc-learning:guide:auto')).toBe('false');
  download.mockRestore();
});
